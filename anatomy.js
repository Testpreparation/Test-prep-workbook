// 配列をシャッフルするアルゴリズム（Fisher-Yatesシャッフル）
function shuffleArray(array) {
const result = [...array];
for (let i = result.length - 1; i > 0; i--) {
const j = Math.floor(Math.random() * (i + 1));
[result[i], result[j]] = [result[j], result[i]];
}
return result;
}

// リロード（読み込み）のたびに問題順と選択肢順（位置）をそれぞれランダムに入れ替える関数
function generateRandomizedQuizData() {
// 1. 問題の出題順をランダム化
const shuffledQuestions = shuffleArray(ANATOMY_RAW_DATA);

return shuffledQuestions.map((item) => {
// 2. 問題ごとに選択肢の位置（順序）をランダム化
const shuffledOptsText = shuffleArray(item.options);

// シャッフル後の正解テキストのインデックス位置（0, 1, 2, 3...）を取得
const correctIndex = shuffledOptsText.indexOf(item.answerText);

// 3. ランダムに並び替えた選択肢の文頭に「1. 」「2. 」「3. 」などの番号を割り当てる
const formattedOptions = shuffledOptsText.map((text, idx) => `${idx + 1}. ${text}`);

return {
q: item.q,
options: formattedOptions,
answer: correctIndex, // シャッフル後の正解のインデックス位置
exp: item.exp
};
});
}

