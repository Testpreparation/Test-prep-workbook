/**
 * HTMLから呼び出される問題取得関数
 * @param {string} roundVal - "1"〜"10"、"quiz"、"comprehensive"、または "all"
 * @returns {Array} 該当する問題の配列
 */
window.getNursingQuestions = function(roundVal) {
  if (typeof lessonData === 'undefined') return [];
  let results = [];
  
  // "all" または "comprehensive" (総合問題) が指定された場合は全範囲を取得
  if (roundVal === 'all' || roundVal === 'comprehensive' || !roundVal) {
    Object.keys(lessonData).forEach(key => {
      const roundNum = key;
      const items = lessonData[key].map(q => ({ ...q, round: roundNum }));
      results = results.concat(items);
    });
  } else {
    // 個別の回（"1"〜"10", "quiz" など）が指定された場合
    const key = roundVal.toString();
    if (lessonData[key]) {
      const roundNum = key;
      results = lessonData[key].map(q => ({ ...q, round: roundNum }));
    }
  }
  
  return results;
};