/**
* 配列をランダムにシャッフルする（フィッシャー–イェーツのシャッフル）
*/
function shuffleArray(array) {
const arr = [...array];
for (let i = arr.length - 1; i > 0; i--) {
const j = Math.floor(Math.random() * (i + 1));
[arr[i], arr[j]] = [arr[j], arr[i]];
}
return arr;
}

/**
* 単一の問題の「選択肢」をランダム化し、正解インデックスを修正して返す
*/
function randomizeQuestionOptions(question) {
// 元の選択肢と正解文字列を取得
const originalOptions = question.options;
const correctAnswerText = originalOptions[question.answer];

// 選択肢の並び順をランダム化
const shuffledOptions = shuffleArray(originalOptions);

// 新しい並び順における正解のインデックスを特定
const newAnswerIndex = shuffledOptions.indexOf(correctAnswerText);

return {
...question,
options: shuffledOptions,
answer: newAnswerIndex
};
}

/**
* HTML側から問題を抽出・取得するための関数
* 出題時に「問題順」および「各問題の選択肢順」をランダムに変換して返します。
*
* @param {number|string} sessionNum - 回数（"all" または 数字）
* @returns {Array} ランダム化された問題配列
*/
function getMicrobiologyQuestions(sessionNum = "all") {
let questions = [];

if (sessionNum === "all" || sessionNum === "総合" || sessionNum === "") {
// 全課題からすべての問題を取得
MICROBIOLOGY_DATA.sessions.forEach(session => {
questions = questions.concat(session.questions);
});
} else {
// 指定された課題（例：1〜12）の問題を取得
const targetSession = MICROBIOLOGY_DATA.sessions.find(
s => s.sessionNumber === Number(sessionNum)
);
if (targetSession) {
questions = [...targetSession.questions];
}
}

// 1. 問題の順番をランダムにシャッフル
const shuffledQuestions = shuffleArray(questions);

// 2. 各問題の選択肢の順番をランダムにシャッフルし、正解インデックスを正しく保持
return shuffledQuestions.map(q => randomizeQuestionOptions(q));
}

