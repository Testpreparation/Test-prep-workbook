// 配列をランダムにシャッフルするヘルパー関数
function shuffleArray(array) {
const arr = [...array];
for (let i = arr.length - 1; i > 0; i--) {
const j = Math.floor(Math.random() * (i + 1));
[arr[i], arr[j]] = [arr[j], arr[i]];
}
return arr;
}

// 選択肢（options）をシャッフルし、正解インデックス（answer）を再計算する関数
function processQuestion(q) {
if (!q.options || q.options.length === 0) return q;

const isMultiple = Array.isArray(q.answer);
const originalAnswers = isMultiple ? q.answer : [q.answer];

// 元の選択肢オブジェクトを作成
const indexedOptions = q.options.map((opt, idx) => ({
text: opt,
isCorrect: originalAnswers.includes(idx)
}));

// シャッフル
const shuffledOptions = shuffleArray(indexedOptions);

// 新しい正解インデックスの抽出
const newAnswers = [];
shuffledOptions.forEach((opt, newIdx) => {
if (opt.isCorrect) {
newAnswers.push(newIdx);
}
});

return {
...q,
options: shuffledOptions.map(opt => opt.text),
answer: isMultiple ? newAnswers : newAnswers[0],
isMultiple: isMultiple // 複数選択（正解が2つ以上）かどうかを判定するフラグ
};
}

